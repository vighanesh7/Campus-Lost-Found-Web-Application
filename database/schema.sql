-- Plain-SQL equivalent of the Sequelize migrations (for reference / phpMyAdmin import).
-- Preferred way: npm run migrate (inside backend). Do not run both on the same database.
CREATE DATABASE IF NOT EXISTS campus_lost_found CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campus_lost_found;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL, studentId VARCHAR(30) NOT NULL UNIQUE, department VARCHAR(100), year INT,
  phone VARCHAR(20), profileImage VARCHAR(255), role ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'STUDENT',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE, description VARCHAR(255),
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE items (
  id INT AUTO_INCREMENT PRIMARY KEY, userId INT NOT NULL, categoryId INT NOT NULL,
  type ENUM('LOST','FOUND') NOT NULL, name VARCHAR(120) NOT NULL, description TEXT NOT NULL,
  location VARCHAR(150) NOT NULL, date DATE NOT NULL, time TIME NULL,
  status ENUM('ACTIVE','PENDING','MATCHED','RETURNED','RESOLVED','CLOSED') NOT NULL DEFAULT 'ACTIVE',
  image VARCHAR(255), additionalDetails TEXT, contactPreference ENUM('MESSAGE','EMAIL','PHONE') NOT NULL DEFAULT 'MESSAGE',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  FOREIGN KEY (categoryId) REFERENCES categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  INDEX (type, status), INDEX (categoryId), INDEX (location)
);
CREATE TABLE item_images (
  id INT AUTO_INCREMENT PRIMARY KEY, itemId INT NOT NULL, imagePath VARCHAR(255) NOT NULL, isPrimary BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (itemId) REFERENCES items(id) ON DELETE CASCADE
);
CREATE TABLE favorites (
  id INT AUTO_INCREMENT PRIMARY KEY, userId INT NOT NULL, itemId INT NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (itemId) REFERENCES items(id) ON DELETE CASCADE,
  CONSTRAINT uq_favorites_user_item UNIQUE (userId, itemId)
);
CREATE TABLE conversations (
  id INT AUTO_INCREMENT PRIMARY KEY, itemId INT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (itemId) REFERENCES items(id) ON DELETE SET NULL
);
CREATE TABLE conversation_participants (
  id INT AUTO_INCREMENT PRIMARY KEY, conversationId INT NOT NULL, userId INT NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (conversationId) REFERENCES conversations(id) ON DELETE CASCADE, FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT uq_participant UNIQUE (conversationId, userId)
);
CREATE TABLE messages (
  id INT AUTO_INCREMENT PRIMARY KEY, conversationId INT NOT NULL, senderId INT NOT NULL, message TEXT NOT NULL, readAt DATETIME NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (conversationId) REFERENCES conversations(id) ON DELETE CASCADE, FOREIGN KEY (senderId) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE notifications (
  id INT AUTO_INCREMENT PRIMARY KEY, userId INT NOT NULL,
  type ENUM('ITEM_REPORTED','MATCH_FOUND','MESSAGE','STATUS_CHANGE','ITEM_RESOLVED','ADMIN_ACTION','REMINDER') NOT NULL,
  title VARCHAR(150) NOT NULL, message VARCHAR(500) NOT NULL, relatedItemId INT NULL, isRead BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (relatedItemId) REFERENCES items(id) ON DELETE SET NULL
);
CREATE TABLE reports (
  id INT AUTO_INCREMENT PRIMARY KEY, itemId INT NOT NULL, reportedBy INT NOT NULL,
  reportType ENUM('INAPPROPRIATE','SPAM','DUPLICATE','FALSE_CLAIM','OTHER') NOT NULL, reason TEXT NOT NULL,
  status ENUM('PENDING','REVIEWED','APPROVED','REJECTED','RESOLVED') NOT NULL DEFAULT 'PENDING', adminNotes TEXT,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (itemId) REFERENCES items(id) ON DELETE CASCADE, FOREIGN KEY (reportedBy) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE audit_logs (
  id INT AUTO_INCREMENT PRIMARY KEY, userId INT NULL, action VARCHAR(80) NOT NULL, entity VARCHAR(50) NOT NULL, entityId INT, details TEXT,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (userId) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE item_matches (
  id INT AUTO_INCREMENT PRIMARY KEY, lostItemId INT NOT NULL, foundItemId INT NOT NULL, score INT NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (lostItemId) REFERENCES items(id) ON DELETE CASCADE, FOREIGN KEY (foundItemId) REFERENCES items(id) ON DELETE CASCADE,
  CONSTRAINT uq_match_pair UNIQUE (lostItemId, foundItemId)
);
